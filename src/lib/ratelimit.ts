/**
 * Minimal in-memory sliding-window limiter.
 * LIMITATION: per server instance only. On serverless/multi-instance hosting, replace with a shared store
 * (e.g. Upstash Redis / Vercel KV) before launch. Documented in docs/17-implementation-notes.md.
 */
const hits = new Map<string, number[]>();

export function rateLimit(key: string, limit = 5, windowMs = 10 * 60 * 1000): boolean {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= limit) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) {
    for (const [k, v] of hits) if (v.every((t) => now - t >= windowMs)) hits.delete(k);
  }
  return true;
}
